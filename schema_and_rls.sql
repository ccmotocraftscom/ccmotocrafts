DROP TABLE IF EXISTS public.bike_bookings CASCADE;

CREATE TABLE public.bike_bookings (id bigint generated by default as identity primary key, created_at timestamp with time zone default timezone('utc'::text, now()) not null, booking_id text, customer_name text not null, phone text not null, email text, bike_model text, area text, service_type text);

GRANT USAGE ON SCHEMA public TO anon, authenticated, public;
GRANT ALL ON TABLE public.bike_bookings TO anon, authenticated, public;
GRANT ALL ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated, public;

ALTER TABLE public.bike_bookings ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Allow public anonymous bike bookings insert" ON public.bike_bookings FOR INSERT TO public, anon, authenticated WITH CHECK (true);

CREATE POLICY "Allow authenticated view bike bookings" ON public.bike_bookings FOR SELECT TO public, anon, authenticated USING (true);

NOTIFY pgrst, 'reload schema';
